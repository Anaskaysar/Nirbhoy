"""
Privacy helpers: field encryption, receipt codes, and photo metadata removal.
"""

import base64
import hashlib
import hmac
import io
import secrets

from cryptography.fernet import Fernet, InvalidToken
from django.conf import settings
from django.core.files.uploadedfile import InMemoryUploadedFile
from django.db import models
from PIL import Image, UnidentifiedImageError

# ---------------------------------------------------------------------------
# Encryption at rest
# ---------------------------------------------------------------------------


def _fernet() -> Fernet:
    key = settings.FIELD_ENCRYPTION_KEY
    try:
        return Fernet(key.encode())
    except ValueError:
        # Not a Fernet-format key (e.g. a random secret generated by the host).
        # Derive a valid 32-byte key from it, so any long random string works.
        derived = base64.urlsafe_b64encode(hashlib.sha256(key.encode()).digest())
        return Fernet(derived)


class EncryptedTextField(models.TextField):
    """
    Stores text encrypted with Fernet (AES + HMAC). If the database file leaks,
    report contents cannot be read without FIELD_ENCRYPTION_KEY.
    The trade-off: encrypted columns cannot be searched or filtered in SQL.
    """

    def get_prep_value(self, value):
        value = super().get_prep_value(value)
        if value is None or value == "":
            return value
        return _fernet().encrypt(value.encode()).decode()

    def from_db_value(self, value, expression, connection):
        if value is None or value == "":
            return value
        try:
            return _fernet().decrypt(value.encode()).decode()
        except InvalidToken:
            return "[unreadable: wrong encryption key]"


# ---------------------------------------------------------------------------
# Receipt codes
# ---------------------------------------------------------------------------

# No 0/O, 1/I/L, so codes are easy to read aloud or copy by hand.
_ALPHABET = "23456789ABCDEFGHJKMNPQRSTUVWXYZ"


def generate_receipt_code() -> str:
    """Random code like NB-7K3M-Q9TX-4HPA (12 random chars, about 59 bits)."""
    chars = "".join(secrets.choice(_ALPHABET) for _ in range(12))
    return f"NB-{chars[0:4]}-{chars[4:8]}-{chars[8:12]}"


def normalize_receipt_code(code: str) -> str:
    """Accept 'nb-7k3m-q9tx-4hpa', 'NB7K3MQ9TX4HPA' or '7K3MQ9TX4HPA'."""
    cleaned = "".join(ch for ch in code.upper() if ch.isalnum())
    if len(cleaned) == 14 and cleaned.startswith("NB"):
        cleaned = cleaned[2:]
    if len(cleaned) != 12 or any(ch not in _ALPHABET for ch in cleaned):
        return ""
    return f"NB-{cleaned[0:4]}-{cleaned[4:8]}-{cleaned[8:12]}"


def hash_receipt_code(code: str) -> str:
    """
    Only this keyed hash is stored. Even someone with database access cannot
    turn a stored row back into the reporter's receipt code.
    """
    return hmac.new(
        settings.RECEIPT_HASH_KEY.encode(), code.encode(), hashlib.sha256
    ).hexdigest()


# ---------------------------------------------------------------------------
# Photos
# ---------------------------------------------------------------------------

MAX_PHOTO_BYTES = 5 * 1024 * 1024
ALLOWED_FORMATS = {"JPEG": "jpg", "PNG": "png", "WEBP": "webp"}


class PhotoError(ValueError):
    pass


def clean_photo(upload) -> tuple[InMemoryUploadedFile, str]:
    """
    Validate an uploaded image and re-encode only its pixels.
    This drops EXIF data (GPS location, phone model, timestamps) that could
    identify the person who took the photo.
    Returns (clean file, format name).
    """
    if upload.size > MAX_PHOTO_BYTES:
        raise PhotoError("Each photo must be 5 MB or smaller.")
    try:
        img = Image.open(upload)
        img.verify()  # detects truncated or fake image files
        upload.seek(0)
        img = Image.open(upload)
        fmt = img.format
    except (UnidentifiedImageError, OSError, SyntaxError):
        raise PhotoError("File is not a valid image.")
    if fmt not in ALLOWED_FORMATS:
        raise PhotoError("Only JPEG, PNG or WEBP images are allowed.")

    mode = "RGBA" if img.mode in ("RGBA", "LA", "P") and fmt != "JPEG" else "RGB"
    pixels_only = Image.new(mode, img.size)
    pixels_only.putdata(list(img.convert(mode).getdata()))

    out = io.BytesIO()
    pixels_only.save(out, format=fmt, quality=88)
    out.seek(0)
    ext = ALLOWED_FORMATS[fmt]
    # Random file name: the original name ("IMG_2031_Rahim.jpg") is discarded.
    name = f"{secrets.token_hex(16)}.{ext}"
    clean = InMemoryUploadedFile(
        out, "photo", name, f"image/{ext.replace('jpg', 'jpeg')}", out.getbuffer().nbytes, None
    )
    return clean, fmt
